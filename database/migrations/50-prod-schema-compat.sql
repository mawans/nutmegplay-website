alter table public.announcement
    add column if not exists title text;

alter table public.accounts
    add column if not exists role text;

alter table public.matchs
    add column if not exists score_home integer,
    add column if not exists score_away integer,
    add column if not exists score_challanger integer,
    add column if not exists score_opponent integer;

update public.accounts
set role = case
    when lower(coalesce(role, '')) in ('player', 'instructor', 'admin') then lower(role)
    when lower(coalesce(login_type, '')) in ('player', 'instructor', 'admin') then lower(login_type)
    else 'player'
end
where role is null
   or lower(coalesce(role, '')) not in ('player', 'instructor', 'admin');

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'accounts_role_check'
          and conrelid = 'public.accounts'::regclass
    ) then
        alter table public.accounts
            add constraint accounts_role_check
            check (role in ('player', 'instructor', 'admin') or role is null);
    end if;
end $$;

-- ---------------------------------------------------------------------------
-- 3. Convert match_stats.match_id to bigint safely
--    Preserve any legacy values in legacy_match_id_uuid
-- ---------------------------------------------------------------------------

do $$
declare
    current_type text;
begin
    select pg_catalog.format_type(a.atttypid, a.atttypmod)
      into current_type
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname = 'match_stats'
      and a.attname = 'match_id'
      and not a.attisdropped;

    if current_type is null then
        raise notice 'match_stats.match_id was not found.';
    elsif current_type <> 'bigint' then
        if not exists (
            select 1
            from information_schema.columns
            where table_schema = 'public'
              and table_name = 'match_stats'
              and column_name = 'legacy_match_id_uuid'
        ) then
            alter table public.match_stats rename column match_id to legacy_match_id_uuid;
            alter table public.match_stats add column match_id bigint;
            alter table public.match_stats alter column legacy_match_id_uuid drop not null;

            update public.match_stats
            set match_id = case
                when trim(legacy_match_id_uuid::text, '"') ~ '^[0-9]+$'
                    then trim(legacy_match_id_uuid::text, '"')::bigint
                else null
            end;

            raise notice 'match_stats.match_id migrated to bigint. Legacy values preserved in legacy_match_id_uuid.';
        end if;
    end if;
end $$;

do $$
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'match_stats'
          and column_name = 'legacy_match_id_uuid'
          and is_nullable = 'NO'
    ) then
        alter table public.match_stats alter column legacy_match_id_uuid drop not null;
    end if;
end $$;

alter table public.match_stats
    add column if not exists distance numeric(8,2) not null default 0,
    add column if not exists passes integer not null default 0,
    add column if not exists dribbles integer not null default 0,
    add column if not exists duels integer not null default 0;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'match_stats_match_id_fkey'
          and conrelid = 'public.match_stats'::regclass
    ) then
        alter table public.match_stats
            add constraint match_stats_match_id_fkey
            foreign key (match_id) references public.matchs(id) on delete cascade;
    end if;
exception
    when duplicate_object then null;
end $$;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'match_stats_match_user_key'
          and conrelid = 'public.match_stats'::regclass
    ) then
        if not exists (
            select 1
            from public.match_stats
            where match_id is not null
            group by match_id, user_id
            having count(*) > 1
        ) then
            alter table public.match_stats
                add constraint match_stats_match_user_key unique (match_id, user_id);
        else
            raise notice 'Skipped match_stats_match_user_key because duplicate (match_id, user_id) rows already exist.';
        end if;
    end if;
end $$;

do $$
begin
    if not exists (
        select 1
        from pg_constraint
        where conname = 'match_stats_result_check'
          and conrelid = 'public.match_stats'::regclass
    ) then
        alter table public.match_stats
            add constraint match_stats_result_check
            check (result in ('win', 'draw', 'loss') or result is null);
    end if;
end $$;

