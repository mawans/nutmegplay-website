-- NutmegPlay production compatibility migration
--
-- Purpose:
-- - Safely align an older/live production schema with the current PHP app
-- - Avoid destructive casts that could orphan existing data
-- - Preserve legacy UUID match references in backup columns for manual review
--
-- Important:
-- - This is intended for an existing production database.
-- - Do NOT run database/init/00-hosted-bootstrap.sql on a live production schema.
-- - Review the notices after execution, especially around legacy UUID match ids.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- 1. Missing supporting tables used by the current app
-- ---------------------------------------------------------------------------

create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null,
    type text not null default 'general',
    title text not null,
    message text,
    icon text default 'notifications',
    link text,
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.challenge_templates (
    id bigint generated by default as identity primary key,
    title text not null,
    description text,
    type text not null default 'daily',
    xp_reward integer not null default 50,
    target_value integer not null default 1,
    metric text not null default 'goals',
    start_date date,
    end_date date,
    is_active boolean not null default true,
    created_by uuid,
    created_at timestamptz not null default now(),
    constraint challenge_templates_type_check check (type in ('daily', 'weekly', 'monthly'))
);

create table if not exists public.match_video_analysis (
    id uuid primary key default gen_random_uuid(),
    match_id bigint not null unique references public.matchs(id) on delete cascade,
    video_url text,
    video_source_type text not null default 'local_upload',
    processing_status text not null default 'pending',
    ai_output jsonb,
    team_stats jsonb,
    player_stats jsonb,
    normalized_stats jsonb,
    error_message text,
    progress_stage text,
    progress_percent integer not null default 0,
    progress_message text,
    uploaded_by uuid,
    queued_at timestamptz not null default now(),
    processed_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.match_jersey_slots (
    id bigint generated by default as identity primary key,
    match_id bigint not null references public.matchs(id) on delete cascade,
    team_color text not null,
    jersey_number integer not null,
    player_uid uuid,
    player_name text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint match_jersey_slots_team_number_check check (
        (team_color = 'blue' and jersey_number between 1 and 5)
        or
        (team_color = 'red' and jersey_number between 6 and 10)
    ),
    constraint match_jersey_slots_match_number_key unique (match_id, jersey_number)
);

create table if not exists public.match_jersey_stats (
    id bigint generated by default as identity primary key,
    match_id bigint not null references public.matchs(id) on delete cascade,
    team_color text not null,
    jersey_number integer not null,
    player_uid uuid,
    player_name text,
    goals integer not null default 0,
    assists integer not null default 0,
    distance_meters integer not null default 0,
    sprints integer not null default 0,
    successful_passes integer not null default 0,
    passes_attempted integer not null default 0,
    successful_dribbles integer not null default 0,
    dribbles_attempted integer not null default 0,
    interceptions integer not null default 0,
    duels_won integer not null default 0,
    shots integer not null default 0,
    top_speed_kmh numeric(8,2) not null default 0,
    minutes_played integer not null default 0,
    clean_sheet boolean not null default false,
    match_winning_goal boolean not null default false,
    team_win_streak integer not null default 0,
    result text,
    raw_player_key text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint match_jersey_stats_team_number_check check (
        (team_color = 'blue' and jersey_number between 1 and 5)
        or
        (team_color = 'red' and jersey_number between 6 and 10)
    ),
    constraint match_jersey_stats_match_number_key unique (match_id, jersey_number),
    constraint match_jersey_stats_result_check check (result in ('win', 'draw', 'loss') or result is null)
);

